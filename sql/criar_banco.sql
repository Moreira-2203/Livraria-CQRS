-- =========================================================
-- 1. USUARIOS
-- =========================================================

CREATE TABLE usuarios (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_usuario VARCHAR(100) NOT NULL UNIQUE,
    senha_hash VARCHAR(255) NOT NULL,
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- =========================================================
-- 2. CLIENTES
-- =========================================================

CREATE TABLE clientes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    email VARCHAR(150) UNIQUE,
    telefone VARCHAR(20),
    cidade VARCHAR(150),
    estado VARCHAR(2),
    membro_desde DATE
);

-- =========================================================
-- 3. AUTORES
-- =========================================================

CREATE TABLE autores (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    nacionalidade VARCHAR(100),
    ano_nascimento INTEGER
);

-- =========================================================
-- 4. CATEGORIAS
-- =========================================================

CREATE TABLE categorias (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL UNIQUE,
    descricao TEXT
);

-- =========================================================
-- 5. LIVROS
-- =========================================================

CREATE TABLE livros (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(200) NOT NULL,
    isbn VARCHAR(20) UNIQUE,
    preco NUMERIC(10,2) NOT NULL
        CHECK (preco >= 0),
    estoque INTEGER NOT NULL DEFAULT 0
        CHECK (estoque >= 0),
    ano_publicacao INTEGER,
    avaliacao_media NUMERIC(3,2)
);

-- =========================================================
-- 6. LIVROS - AUTORES
-- =========================================================

CREATE TABLE livros_autores (
    livro_id INTEGER NOT NULL,
    autor_id INTEGER NOT NULL,

    PRIMARY KEY (livro_id, autor_id),

    FOREIGN KEY (livro_id)
        REFERENCES livros(id),

    FOREIGN KEY (autor_id)
        REFERENCES autores(id)
);

-- =========================================================
-- 7. LIVROS - CATEGORIAS
-- =========================================================

CREATE TABLE livros_categorias (
    livro_id INTEGER NOT NULL,
    categoria_id INTEGER NOT NULL,

    PRIMARY KEY (livro_id, categoria_id),

    FOREIGN KEY (livro_id)
        REFERENCES livros(id),

    FOREIGN KEY (categoria_id)
        REFERENCES categorias(id)
);

-- =========================================================
-- 8. PEDIDOS
-- =========================================================

CREATE TABLE pedidos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id INTEGER NOT NULL,
    data_pedido TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(30) NOT NULL DEFAULT 'processando',

    FOREIGN KEY (cliente_id)
        REFERENCES clientes(id)
);

-- =========================================================
-- 9. ITENS DO PEDIDO
-- =========================================================

CREATE TABLE itens_pedido (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id INTEGER NOT NULL,
    livro_id INTEGER NOT NULL,
    quantidade INTEGER NOT NULL
        CHECK (quantidade > 0),
    preco_unitario NUMERIC(10,2) NOT NULL
        CHECK (preco_unitario >= 0),

    FOREIGN KEY (pedido_id)
        REFERENCES pedidos(id)
        ON DELETE CASCADE,

    FOREIGN KEY (livro_id)
        REFERENCES livros(id),

    UNIQUE (pedido_id, livro_id)
);

-- =========================================================
-- INDICES
-- =========================================================

CREATE INDEX idx_pedidos_cliente
    ON pedidos(cliente_id);

CREATE INDEX idx_itens_pedido
    ON itens_pedido(pedido_id);

CREATE INDEX idx_itens_livro
    ON itens_pedido(livro_id);

